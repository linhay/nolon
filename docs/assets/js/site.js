function setLanguage(lang) {
  const selected = dict[lang] ? lang : "zh";
  const table = dict[selected];
  document.documentElement.lang = selected === "zh" ? "zh-CN" : "en";
  localStorage.setItem("lang", selected);

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (table[key]) {
      el.textContent = table[key];
    }
  });

  document.querySelectorAll(".lang-switch button").forEach((btn) => {
    btn.classList.toggle("active", btn.dataset.lang === selected);
  });
}

function bindLanguageSwitch() {
  document.querySelectorAll(".lang-switch button").forEach((btn) => {
    btn.addEventListener("click", () => setLanguage(btn.dataset.lang));
  });
}

function bindNavActive() {
  const links = Array.from(document.querySelectorAll(".nav a"));
  const sectionIds = links.map((link) => link.getAttribute("href")).filter(Boolean);

  const io = new IntersectionObserver((entries) => {
    entries.forEach((entry) => {
      if (!entry.isIntersecting) return;
      const id = `#${entry.target.id}`;
      links.forEach((link) => {
        link.classList.toggle("active", link.getAttribute("href") === id);
      });
    });
  }, { rootMargin: "-35% 0px -55% 0px", threshold: 0.01 });

  sectionIds.forEach((id) => {
    const sec = document.querySelector(id);
    if (sec) io.observe(sec);
  });
}

function bindMobileMenu() {
  const button = document.querySelector("[data-menu-toggle]");
  if (!button) return;
  button.addEventListener("click", () => {
    const next = !document.body.classList.contains("nav-open");
    document.body.classList.toggle("nav-open", next);
    button.setAttribute("aria-expanded", String(next));
  });
}

function bindTracking() {
  document.querySelectorAll("[data-track]").forEach((el) => {
    el.addEventListener("click", () => {
      const eventName = el.getAttribute("data-track");
      if (!eventName) return;
      if (window.console && window.console.info) {
        window.console.info(`[nolon-site] click:${eventName}`);
      }
    });
  });
}

function detectPlatformAndSetDownload() {
  const mainBtn = document.getElementById("main-download-btn");
  const altContainer = document.getElementById("download-alt");
  const altLink = document.getElementById("alt-download-link");
  if (!mainBtn || !altContainer || !altLink) return;

  const ua = window.navigator.userAgent;
  const isIntel = ua.includes("Intel Mac OS X") && !ua.includes("ARM");
  
  const armUrl = "https://github.com/linhay/nolon/releases/download/v2.1.0/nolon-arm64.dmg";
  const x86Url = "https://github.com/linhay/nolon/releases/download/v2.1.0/nolon-x86_64.dmg";

  if (isIntel) {
    mainBtn.href = x86Url;
    altLink.href = armUrl;
    altLink.textContent = "Apple Silicon (ARM64)";
  } else {
    // 默认 ARM64 或自动检测为 ARM
    mainBtn.href = armUrl;
    altLink.href = x86Url;
    altLink.textContent = "Intel (x86_64)";
  }

  altContainer.style.opacity = "1";
}

function initYear() {
  const el = document.getElementById("year");
  if (el) el.textContent = new Date().getFullYear();
}

function bindFaqToggle() {
  document.querySelectorAll(".faq-question").forEach((q) => {
    q.addEventListener("click", () => {
      const item = q.parentElement;
      const isOpen = item.classList.contains("open");
      
      // Close all others
      document.querySelectorAll(".faq-item").forEach((i) => {
        i.classList.remove("open");
        const ans = i.querySelector(".faq-answer");
        if (ans) ans.style.display = "none";
      });
      
      if (!isOpen) {
        item.classList.add("open");
        const ans = item.querySelector(".faq-answer");
        if (ans) ans.style.display = "block";
      }
    });
  });
}

(function init() {
  initYear();
  bindLanguageSwitch();
  bindNavActive();
  bindMobileMenu();
  bindTracking();
  bindFaqToggle();
  detectPlatformAndSetDownload();
  setLanguage(localStorage.getItem("lang") || "zh");
})();
